Import ListNotations.

(* A range-shaped WRITE, which is the other half of what an ordered
   dictionary is for.  Ex_Range.v reads a range; this file deletes one.

   let mut orders := orders_tbl in
   foreach q in queries do
       if q.type = 0 then
           orders := q.new_order :: !orders
       else if q.type = 1 then
           let n = len [ o <- !orders,
                         check(!(o.price < q.lo) && o.price < q.hi),
                         ret o ] in
           outputs := str(n) :: !outputs
       else
           (* withdraw a price band: keep the rows OUTSIDE it *)
           orders := [ o <- !orders,
                       check(!(!(o.price < q.lo) && o.price < q.hi)),
                       ret o ]
   end

   Written by hand, not generated by an LLM.

   The point of the third branch is that a programmer writes the removal of
   a band as the NEGATION of the band's own test, and that negation is the
   complement the index can take in one operation.  A one-sided removal
   needs no complement -- dropping every key below a bound is restricting to
   [lo, inf) -- so the operator this file witnesses, ODictRangeDelete, is
   needed exactly for the two-sided case. *)

Definition row_ty_orders :=
  TRecord (record_sort [("id", TInt); ("price", TInt)]).

Definition query_ty :=
  TRecord (record_sort [("type", TInt); ("new_order", row_ty_orders);
                        ("lo", TInt); ("hi", TInt)]).

Section WithConcreteMaps.
  Context {width: Z} {word: word.word width} {word_ok: word.ok word}.
  Notation value := (value (width:=width)).

  Local Open Scope string.

  Instance ctenv : map.map string type := SortedListString.map _.
  Instance ctenv_ok : map.ok ctenv := SortedListString.ok _.

  Instance clocals : map.map string value := SortedListString.map _.
  Instance clocals_ok : map.ok clocals := SortedListString.ok _.

  (* lo <= o.price < hi, as a programmer writes it with no index in mind *)
  Definition in_band : expr :=
    EBinop OAnd
      (EUnop ONot (EBinop OLess (EAccess (EVar "o") "price")
                     (EAccess (EVar "q") "lo")))
      (EBinop OLess (EAccess (EVar "o") "price") (EAccess (EVar "q") "hi")).

  Definition keep (pred : expr) : expr :=
    EFlatmap LikeList (ELoc "orders") "o"
      (EIf pred (EBinop OCons (EVar "o") (EAtom (ANil None))) (EAtom (ANil None))).

  Definition prog : command :=
    CLetMut (EVar "orders_tbl") "orders"
      (CForeach (EVar "queries") "q"
         (CIf (EBinop OEq (EAccess (EVar "q") "type") (EAtom (AInt 0)))
            (CAssign "orders"
               (EBinop OCons (EAccess (EVar "q") "new_order") (ELoc "orders")))
            (CIf (EBinop OEq (EAccess (EVar "q") "type") (EAtom (AInt 1)))
               (CLet (EUnop OLength (keep in_band)) "n"
                  (CAssign "outputs"
                     (EBinop OCons (EUnop OIntToString (EVar "n"))
                        (ELoc "outputs"))))
               (CAssign "orders" (keep (EUnop ONot in_band)))))).

  Definition init_Gstore : ctenv :=
    map.put map.empty "outputs" (TList TString).

  Definition init_Genv : ctenv :=
    map.put (map.put map.empty "orders_tbl" (TList row_ty_orders))
      "queries" (TList query_ty).

  Compute (typecheck init_Gstore init_Genv prog).

  Definition heuristics :=
    [ AC [PushdownCollection; AnnotateCollection; IfNilIntoFlatmap]
        [[RangedDictIdx "price"]] ].

  Definition prog_transformed :=
    map (fun heu => apply_optimize_anno (width:=width) (heu prog) init_Gstore init_Genv)
      heuristics.

  (* ---- projections, so every claim below is an equality of closed terms
         and reduces with vm_compute ---- *)

  Definition installed_fields (c : command) : list string :=
    match c with
    | CLetMut (ERecord l) _ _ => List.map fst l
    | _ => []
    end.

  Definition install_of (c : command) : option expr :=
    match c with CLetMut e _ _ => Some e | _ => None end.

  Definition insert_of (c : command) : option expr :=
    match c with
    | CLetMut _ _ (CForeach _ _ (CIf _ (CAssign _ e) _)) => Some e
    | _ => None
    end.

  Definition query_of (c : command) : option expr :=
    match c with
    | CLetMut _ _ (CForeach _ _ (CIf _ _ (CIf _ (CLet q _ _) _))) => Some q
    | _ => None
    end.

  Definition withdraw_of (c : command) : option expr :=
    match c with
    | CLetMut _ _ (CForeach _ _ (CIf _ _ (CIf _ _ (CAssign _ e)))) => Some e
    | _ => None
    end.

  (* ---- the shapes the claims are stated against ---- *)

  Definition member : expr := EAccess (EAccess (ELoc "orders") "aux_tag") "0".
  Definition new_order : expr := EAccess (EVar "q") "new_order".

  Definition bucket_add (acc_e key_e row_e : expr) : expr :=
    ETernop OInsert acc_e key_e
      (EBinop OBagInsert
         (EOptMatch (EBinop OLookup acc_e key_e)
            (EAtom (AEmptyBag None)) "x" (EVar "x"))
         row_e).

  Definition build_by_price (src : expr) : expr :=
    EFold src (EAtom (AEmptyDict Ranged None)) "tup" "acc"
      (bucket_add (EVar "acc") (EAccess (EVar "tup") "price") (EVar "tup")).

  Definition only_member (e : expr) : expr :=
    ERecord [("aux_tag", ERecord [("0", e)])].

  Definition lo : expr := EUnop OSome (EAccess (EVar "q") "lo").
  Definition hi : expr := EUnop OSome (EAccess (EVar "q") "hi").

  (* One Ranged dict on price, and nothing else: no query and no write reads
     the rows in order, so the erasure pass drops the table's own list and
     the table IS its index. *)
  Lemma installs_the_ranged_dict :
    install_of (nth 0 prog_transformed CSkip)
    = Some (only_member (build_by_price (EVar "orders_tbl"))).
  Proof. vm_compute; reflexivity. Qed.

  Lemma the_table_is_its_index :
    installed_fields (nth 0 prog_transformed CSkip) = ["aux_tag"].
  Proof. vm_compute; reflexivity. Qed.

  (* the insert adds one row to the bucket its price names *)
  Lemma insert_is_incremental :
    insert_of (nth 0 prog_transformed CSkip)
    = Some (only_member
              (ELet member "y"
                 (bucket_add (EVar "y") (EAccess new_order "price") new_order))).
  Proof. vm_compute; reflexivity. Qed.

  (* the read: the buckets of the index restricted to the band *)
  Lemma query_is_a_range_probe :
    query_of (nth 0 prog_transformed CSkip)
    = Some (EACFold AGCount
              (EFlatmap LikeBag
                 (EUnop ODictValues (ETernop ODictRange member lo hi))
                 "b" (EVar "b"))).
  Proof. vm_compute; reflexivity. Qed.

  (* and the write this file exists for: the negation of the band's own test
     is one complement on the index, not a fold over the rows that stay.
     A one-sided removal would not need ODictRangeDelete -- dropping every
     key below a bound is a restriction to [lo, inf), which is what
     eval/Kafka_WindowStore's retention policy compiles to -- so this is the
     operator's own witness. *)
  Lemma withdraw_is_a_range_delete :
    withdraw_of (nth 0 prog_transformed CSkip)
    = Some (only_member (ETernop ODictRangeDelete member lo hi)).
  Proof. vm_compute; reflexivity. Qed.

  Theorem prog_transformed_sem : forall (store env : clocals),
      locals_wf init_Gstore store ->
      locals_wf init_Genv env ->
      forall prog', In prog' prog_transformed ->
                    interp_command store env prog' = interp_command store env prog.
  Proof.
    unfold prog_transformed, heuristics, apply_optimize_anno; cbn [map]; intros.
    repeat destruct_In;
      try eapply transf_sound__preserve_sem;
      eauto using apply_all_transfs_sound with transf_hints.
    lazymatch goal with H: In _ [] |- _ => apply in_nil in H; intuition idtac end.
  Qed.
End WithConcreteMaps.
