Definition prog := (CLetMut (EVar "inventory_tbl") "inventory" (CForeach (EVar "queries") "q" (CIf (EBinop OEq (EAccess (EVar "q") "type") (EAtom (AString "add"))) (CAssign "inventory" (EBinop OCons (EAccess (EVar "q") "item") (ELoc "inventory"))) (CIf (EBinop OEq (EAccess (EVar "q") "type") (EAtom (AString "remove"))) (CAssign "inventory" (EFlatmap LikeList (ELoc "inventory") "item" (EIf (EUnop ONot (EBinop OEq (EAccess (EVar "item") "id") (EAccess (EVar "q") "id"))) (EBinop OCons (EVar "item") (EAtom (ANil None))) (EAtom (ANil None))))) (CAssign "log" (EBinop OCons (ESort LikeList (EFlatmap LikeList (ELoc "inventory") "item" (EIf (EBinop OEq (EAccess (EVar "item") "id") (EAccess (EVar "q") "id")) (EBinop OCons (EAccess (EVar "item") "price") (EAtom (ANil None))) (EAtom (ANil None))))) (ELoc "log"))))))).

(* Hand-written, not generated by an LLM *)
Definition heuristics :=
  [ AC [PushdownCollection; AnnotateCollection; IfNilIntoFlatmap]
      [[DictIdx "id"]]
  ].

Definition row_ty_inventory :=
  TRecord (record_sort [("id", TInt); ("price", TInt)]).

Definition row_ty_query :=
  TRecord (record_sort [("type", TString); ("id", TInt); ("item", row_ty_inventory)]).

Section WithConcreteMaps.
  Context {width: Z} {word: word.word width} {word_ok: word.ok word}.
  Notation value := (value (width:=width)).

  Local Open Scope string.

  Instance ctenv : map.map string type := SortedListString.map _.
  Instance ctenv_ok : map.ok ctenv := SortedListString.ok _.

  Instance clocals : map.map string value := SortedListString.map _.
  Instance clocals_ok : map.ok clocals := SortedListString.ok _.

  Definition init_Gstore : ctenv :=
    map.put map.empty "log" (TList (TList TInt)).

  Definition init_Genv : ctenv :=
    map.put (map.put map.empty
               "inventory_tbl" (TList row_ty_inventory))
      "queries" (TList row_ty_query).

  Compute (typecheck init_Gstore init_Genv prog).

  Definition prog_transformed := map (fun heu => apply_optimize_anno (width:=width) (heu prog) init_Gstore init_Genv) heuristics.

  Compute prog_transformed.

  Theorem prog_transformed_sem : forall (store env : clocals),
      locals_wf init_Gstore store ->
      locals_wf init_Genv env ->
      forall prog', In prog' prog_transformed ->
                    interp_command store env prog' = interp_command store env prog.
  Proof.
    unfold prog_transformed, heuristics, apply_optimize_anno; cbn [map]; intros.
    repeat destruct_In;
      try eapply transf_sound__preserve_sem;
      eauto using apply_all_transfs_sound with transf_hints.
    lazymatch goal with H: In _ [] |- _ => apply in_nil in H; intuition idtac end.
  Qed.
End WithConcreteMaps.

Compute program_py prog.
