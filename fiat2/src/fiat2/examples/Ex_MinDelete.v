(*
(* The minimum of an attribute, under deletes keyed on that same attribute.

   The minimum alone cannot be maintained: deleting the rows at the minimum
   price leaves nothing to fall back on.  Choosing a set index on the same
   attribute beside the min aggregation gives the fallback, and the min
   aggregation is still what a read goes to. *)

let mut orders := orders_tbl in

foreach q in queries do
    if q.type = 0 then
        orders := [ o <- !orders, check(!(o.price = q.price)), ret o ]
    else if q.type = 1 then
        orders := q.new_order :: !orders
    else
        let min_price_opt = min([ o <- !orders, ret o.price ]) in
        outputs :=
            (optmatch min_price_opt as min_price with
             | None => "No orders\n"
             | Some min_price => "Minimum price: " ++ str(min_price) ++ "\n") :: !outputs
end
*)

(* Hand-written, not generated by an LLM *)
Definition prog :=
  CLetMut (EVar "orders_tbl") "orders"
    (CForeach (EVar "queries") "q"
       (CIf (EBinop OEq (EAccess (EVar "q") "type") (EAtom (AInt 0)))
          (CAssign "orders"
             (EFlatmap LikeList (ELoc "orders") "o"
                (EIf (EUnop ONot (EBinop OEq (EAccess (EVar "o") "price")
                                    (EAccess (EVar "q") "price")))
                   (EBinop OCons (EVar "o") (EAtom (ANil None)))
                   (EAtom (ANil None)))))
          (CIf (EBinop OEq (EAccess (EVar "q") "type") (EAtom (AInt 1)))
             (CAssign "orders"
                (EBinop OCons (EAccess (EVar "q") "new_order") (ELoc "orders")))
          (CLet (EFold (EFlatmap LikeList (ELoc "orders") "o"
                          (EBinop OCons (EAccess (EVar "o") "price") (EAtom (ANil None))))
                   (EAtom (ANone (Some TInt))) "_v" "_acc"
                   (EOptMatch (EVar "_acc") (EUnop OSome (EVar "_v")) "_x"
                      (EIf (EBinop OLess (EVar "_v") (EVar "_x"))
                         (EUnop OSome (EVar "_v")) (EVar "_acc"))))
             "min_price_opt"
             (CAssign "outputs"
                (EBinop OCons
                   (EOptMatch (EVar "min_price_opt")
                      (EAtom (AString "No orders\n")) "min_price"
                      (EBinop OConcatString (EAtom (AString "Minimum price: "))
                         (EBinop OConcatString (EUnop OStringOfInt (EVar "min_price"))
                            (EAtom (AString "\n")))))
                   (ELoc "outputs"))))))).

(* Three configurations.

   0 and 1 show what the set index is for.  The guard rule is the same in both:
   it keeps the cached minimum unless the delete removes it.  What differs is
   the cost of the branch that does not keep it -- with a set index on the same
   attribute it reads that set, and without one it goes back to the table.  The
   set index must be listed first, so that the min aggregation wins the race for
   the read of the minimum.

   2 asks for the other structure that can answer a minimum: an ORDERED
   dictionary keyed on the same attribute.  It is here because the delete in
   this program is a point delete on that attribute, so the dictionary serves
   the delete outright -- one ODelete, no correction term and no recompute,
   which is the whole cost the min aggregation pays in configuration 0.

   What it does NOT serve is the READ of the minimum, and the reason is worth
   stating because it is the one thing this file measures that is a gap rather
   than a result: no rule takes AGMin over the attribute's values to
   ODictMinKey of the dictionary that is keyed on them.  So the read stays a
   scan, and because that scan is the id_tag list's last reader, the list
   survives and the delete keeps rewriting it.  The two facts such a rule needs
   are proved (TypeSound.map_fst_dict_insert and
   DictIndexImpl.map_fst_gallina_to_idx); the rule is not written.

   This makes the comparison a TRADE and not a dominance, which is why the
   selector has no basis to prefer either: 2 is cheaper on the delete and
   dearer on the read.  The rule would turn it into a dominance. *)
Definition heuristics :=
  [ AC [PushdownCollection; AnnotateCollection; IfNilIntoFlatmap]
      [[SetAgg "price"; MinAgg "price"]];
    AC [PushdownCollection; AnnotateCollection; IfNilIntoFlatmap]
      [[MinAgg "price"]];
    AC [PushdownCollection; AnnotateCollection; IfNilIntoFlatmap]
      [[RangedDictIdx "price"]]
  ].

Definition row_ty_orders :=
  TRecord (record_sort [("id", TInt); ("price", TInt)]).

Definition query_ty :=
  TRecord (record_sort [("type", TInt); ("price", TInt); ("new_order", row_ty_orders)]).

Section WithConcreteMaps.
  Notation value := (value).

  Local Open Scope string.

  Instance ctenv : map.map string type := SortedListString.map _.
  Instance ctenv_ok : map.ok ctenv := SortedListString.ok _.

  Instance clocals : map.map string value := SortedListString.map _.
  Instance clocals_ok : map.ok clocals := SortedListString.ok _.

  Definition init_Gstore : ctenv :=
    map.put map.empty "outputs" (TList TString).

  Definition init_Genv : ctenv :=
    map.put (map.put map.empty
               "orders_tbl" (TList row_ty_orders))
      "queries" (TList query_ty).

  Compute (typecheck init_Gstore init_Genv prog).

  Definition prog_transformed := map (fun heu => apply_optimize_anno (heu prog) init_Gstore init_Genv) heuristics.

  Compute prog_transformed.

  Theorem prog_transformed_sem : forall (store env : clocals),
      locals_wf init_Gstore store ->
      locals_wf init_Genv env ->
      forall prog', In prog' prog_transformed ->
                    interp_command store env prog' = interp_command store env prog.
  Proof.
    unfold prog_transformed, heuristics, apply_optimize_anno; cbn [map]; intros.
    repeat destruct_In;
      try eapply transf_sound__preserve_sem;
      eauto using apply_all_transfs_sound with transf_hints.
    lazymatch goal with H: In _ [] |- _ => apply in_nil in H; intuition idtac end.
  Qed.
End WithConcreteMaps.
