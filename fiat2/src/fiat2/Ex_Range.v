Definition prog := (CLetMut (EVar "orders_tbl") "orders" (CForeach (EVar "queries") "q" (CIf (EBinop OEq (EAccess (EVar "q") "type") (EAtom (AInt 0))) (CSeq (CAssign "orders" (EBinop OCons (EAccess (EVar "q") "new_order") (ELoc "orders"))) (CAssign "outputs" (EBinop OCons (EAtom (AString "Order added\n")) (ELoc "outputs")))) (CLet (EUnop OLength (EFlatmap LikeList (ELoc "orders") "o" (EIf (EBinop OAnd (EUnop ONot (EBinop OLess (EAccess (EVar "o") "price") (EAccess (EVar "q") "lo"))) (EBinop OLess (EAccess (EVar "o") "price") (EAccess (EVar "q") "hi"))) (EBinop OCons (EVar "o") (EAtom (ANil None))) (EAtom (ANil None))))) "n" (CAssign "outputs" (EBinop OCons (EBinop OConcatString (EAtom (AString "Orders in range: ")) (EBinop OConcatString (EUnop OIntToString (EVar "n")) (EAtom (AString "\n")))) (ELoc "outputs"))))))).

(* Written by hand, not generated by an LLM.

   The same program twice, differing only in the structure the dictionary
   index asks a backend for.  Ranged buys the range rewrite; Unranged does
   not, and the range query stays the scan it was.  Everything else -- the
   install, the point-lookup rule, the insert maintenance -- is identical,
   because every dictionary operator other than ODictRange is kind-generic. *)
Definition heuristics :=
  [ AC [PushdownCollection; AnnotateCollection]
      [[RangedDictIdx "price"]]
  ; AC [PushdownCollection; AnnotateCollection]
      [[DictIdx "price"]]
  ].

Definition row_ty_orders :=
  TRecord (record_sort [("id", TInt); ("price", TInt)]).

Definition query_ty :=
  TRecord (record_sort [("type", TInt); ("new_order", row_ty_orders); ("lo", TInt); ("hi", TInt)]).

Section WithConcreteMaps.
  Context {width: Z} {word: word.word width} {word_ok: word.ok word}.
  Notation value := (value (width:=width)).

  Local Open Scope string.

  Instance ctenv : map.map string type := SortedListString.map _.
  Instance ctenv_ok : map.ok ctenv := SortedListString.ok _.

  Instance clocals : map.map string value := SortedListString.map _.
  Instance clocals_ok : map.ok clocals := SortedListString.ok _.

  Definition init_Gstore : ctenv :=
    map.put map.empty "outputs" (TList TString).

  Definition init_Genv : ctenv :=
    map.put (map.put map.empty
               "orders_tbl" (TList row_ty_orders))
      "queries" (TList query_ty).

  Compute (typecheck init_Gstore init_Genv prog).

  Definition prog_transformed := map (fun heu => apply_optimize_anno (width:=width) (heu prog) init_Gstore init_Genv) heuristics.

  Compute prog_transformed.

  (* The query the Ranged index answers: the buckets of the index restricted
     to the key range, counted.  No row is looked at outside the range. *)
  Definition range_probe : expr :=
    EACFold AGCount
      (EFlatmap LikeBag
         (EUnop ODictValues
            (ETernop ODictRange
               (EAccess (EAccess (ELoc "orders") "aux_tag") "0")
               (EUnop OSome (EAccess (EVar "q") "lo"))
               (EUnop OSome (EAccess (EVar "q") "hi"))))
         "b" (EVar "b")).

  (* The same query with an Unranged index: the source filter, unchanged,
     over the table's list. *)
  Definition range_scan : expr :=
    EACFold AGCount
      (EFlatmap LikeBag (EBagOf (EAccess (ELoc "orders") "id_tag")) "o"
         (EIf
            (EBinop OAnd
               (EUnop ONot (EBinop OLess (EAccess (EVar "o") "price")
                              (EAccess (EVar "q") "lo")))
               (EBinop OLess (EAccess (EVar "o") "price")
                  (EAccess (EVar "q") "hi")))
            (EBinop OBagInsert (EAtom (AEmptyBag None)) (EVar "o"))
            (EAtom (AEmptyBag None)))).

  (* Two projections, so the claims below are equalities of closed terms and
     reduce with vm_compute instead of unifying a whole program against a
     pattern full of holes. *)

  (* which fields the table's record holds after installation *)
  Definition installed_fields (c : command) : list string :=
    match c with
    | CLetMut (ERecord l) _ _ => List.map fst l
    | _ => []
    end.

  (* the expression the query branch binds *)
  Definition query_of (c : command) : option expr :=
    match c with
    | CLetMut _ _ (CForeach _ _ (CIf _ _ (CLet q _ _))) => Some q
    | _ => None
    end.

  (* RangedDictIdx: the range rewrite fires. *)
  Lemma ranged_probes :
    query_of (nth 0 prog_transformed CSkip) = Some range_probe.
  Proof. vm_compute; reflexivity. Qed.

  (* And then nothing reads the table's list any more, so the erasure pass
     drops id_tag outright: the table IS its index. *)
  Lemma ranged_drops_the_list :
    installed_fields (nth 0 prog_transformed CSkip) = ["aux_tag"].
  Proof. vm_compute; reflexivity. Qed.

  (* DictIdx: it does not.  ODictRange is the one operator whose typing pins
     the kind, so on the Unranged member the rule is the identity and the
     query is left as the scan it was. *)
  Lemma unranged_scans :
    query_of (nth 1 prog_transformed CSkip) = Some range_scan.
  Proof. vm_compute; reflexivity. Qed.

  (* And because that scan still reads the list, the list stays. *)
  Lemma unranged_keeps_the_list :
    installed_fields (nth 1 prog_transformed CSkip) = ["id_tag"; "aux_tag"].
  Proof. vm_compute; reflexivity. Qed.

  Theorem prog_transformed_sem : forall (store env : clocals),
      locals_wf init_Gstore store ->
      locals_wf init_Genv env ->
      forall prog', In prog' prog_transformed ->
                    interp_command store env prog' = interp_command store env prog.
  Proof.
    unfold prog_transformed, heuristics, apply_optimize_anno; cbn [map]; intros.
    repeat destruct_In;
      try eapply transf_sound__preserve_sem;
      eauto using apply_all_transfs_sound with transf_hints.
    lazymatch goal with H: In _ [] |- _ => apply in_nil in H; intuition idtac end.
  Qed.
End WithConcreteMaps.

Compute program_py prog.
Compute map program_py prog_transformed.
