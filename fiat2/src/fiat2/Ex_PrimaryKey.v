Require Import fiat2.Language fiat2.Interpret fiat2.Value fiat2.TypeSystem fiat2.TypeSound
  fiat2.TransfSound fiat2.Utils fiat2.Constraint fiat2.ToPython.
Require Import coqutil.Map.Interface coqutil.Map.SortedListString coqutil.Word.Interface
  coqutil.Datatypes.Result.
From Stdlib Require Import String ZArith List.

Import ListNotations.

(* A table with a primary key, loaded one row at a time.

   The table is declared empty, which is where the constraint comes from for
   free: an empty table has distinct keys, so the invariant holds before the
   program runs anything.  Every write to the table is checked, and a write
   that would repeat a key runs the policy instead -- here, recording the
   offending key and leaving the table alone.

let mut users := []            (* primary key: id *)
foreach u in incoming do
    users := u :: !users
      keeping  unique(id)
      else     rejected := u.id :: !rejected
end
*)

(* already sorted by field name, as a record type must be *)
Definition row_ty :=
  TRecord [("id", TInt); ("name", TString)].

(* Hand-written, not generated by an LLM *)
Definition body :=
  CForeach (EVar "incoming") "u"
    (CAssignChecked "users"
       (EBinop OCons (EVar "u") (ELoc "users"))
       (unique_guard "id" "users" "r" TInt)
       (CAssign "rejected"
          (EBinop OCons (EAccess (EVar "u") "id") (ELoc "rejected")))).

Definition prog :=
  CLetMut (EAtom (ANil (Some row_ty))) "users" body.

Section WithConcreteMaps.
  Context {width: Z} {word: word.word width} {word_ok: word.ok word}.
  Notation value := (value (width:=width)).

  Local Open Scope string.

  Instance ctenv : map.map string type := SortedListString.map _.
  Instance ctenv_ok : map.ok ctenv := SortedListString.ok _.

  Instance clocals : map.map string value := SortedListString.map _.
  Instance clocals_ok : map.ok clocals := SortedListString.ok _.

  Definition init_Gstore : ctenv :=
    map.put map.empty "rejected" (TList TInt).

  Definition init_Genv : ctenv :=
    map.put map.empty "incoming" (TList row_ty).

  Compute (typecheck init_Gstore init_Genv prog).

  Definition body_Gstore : ctenv :=
    map.put init_Gstore "users" (TList row_ty).

  Lemma init_Gstore_wf : tenv_wf init_Gstore.
  Proof.
    unfold tenv_wf, init_Gstore; intros x t H.
    destruct (String.eqb x "rejected") eqn:E; rewrite ?eqb_eq, ?eqb_neq in *; subst.
    1:{ rewrite map.get_put_same in H. do_injection. repeat constructor. }
    1:{ rewrite map.get_put_diff in H by congruence.
        rewrite map.get_empty in H; discriminate. }
  Qed.

  Lemma row_ty_wf : type_wf row_ty.
  Proof.
    unfold row_ty.
    repeat constructor; cbn; intuition congruence.
  Qed.

  Lemma body_Gstore_wf : tenv_wf body_Gstore.
  Proof.
    unfold body_Gstore.
    apply tenv_wf_step; auto using init_Gstore_wf.
    constructor; apply row_ty_wf.
  Qed.

  Lemma init_Genv_wf : tenv_wf init_Genv.
  Proof.
    unfold tenv_wf, init_Genv; intros x t H.
    destruct (String.eqb x "incoming") eqn:E; rewrite ?eqb_eq, ?eqb_neq in *; subst.
    1:{ rewrite map.get_put_same in H. do_injection.
        constructor; apply row_ty_wf. }
    1:{ rewrite map.get_put_diff in H by congruence.
        rewrite map.get_empty in H; discriminate. }
  Qed.

  (* Every write the body makes to the table is checked against the key, so the
     body preserves the constraint.  The policy writes to another variable, and
     a write to another variable cannot break this one. *)
  Lemma body_keeps_id_unique :
    parameterized_wf (locals:=clocals) body_Gstore init_Genv
      (value_wf_with_globals (unique_on "id") ["users"]) body.
  Proof.
    unfold body.
    econstructor.
    1:{ constructor. unfold init_Genv. rewrite_map_get_put_goal; reflexivity. }
    eapply unique_checked_assign_wf with
      (rt := [("id", TInt); ("name", TString)])
      (tenv_ok := ctenv_ok) (locals_ok := clocals_ok).
    1: apply body_Gstore_wf.
    1: apply tenv_wf_step; auto using init_Genv_wf, row_ty_wf.
    1: unfold body_Gstore; rewrite_map_get_put_goal; reflexivity.
    1: reflexivity.
    1:{ (* u :: !users is again a table of rows *)
        repeat econstructor.
        all: unfold body_Gstore; repeat rewrite_map_get_put_goal; reflexivity. }
    (* the policy writes to another variable, and a write to another variable
       cannot break this constraint *)
    econstructor.
    2:{ unfold body_Gstore, init_Gstore.
        repeat rewrite_map_get_put_goal; reflexivity. }
    2:{ repeat econstructor.
        all: unfold body_Gstore, init_Gstore;
          repeat rewrite_map_get_put_goal; reflexivity. }
    intros. unfold value_wf_with_globals.
    constructor; [ left; congruence | constructor ].
  Qed.

  (* The constraint holds of the table at every point in its lifetime: the
     declaration establishes it on the empty table, and the body preserves it. *)
  Theorem prog_keeps_id_unique : forall (store env : clocals),
      locals_wf init_Gstore store ->
      locals_wf init_Genv env ->
      holds_for_all_entries (value_wf_with_globals (unique_on "id") ["users"])
        (interp_command (map.put store "users" (VList nil)) env body).
  Proof.
    intros.
    eapply parameterized_wf__preserve_P.
    1: apply body_Gstore_wf.
    1: apply init_Genv_wf.
    1: apply body_keeps_id_unique.
    2: assumption.
    2: apply value_wf_with_globals_put with (locals_ok := clocals_ok),
         unique_on_nil.
    unfold body_Gstore. apply locals_wf_step; auto.
    constructor; auto.
  Qed.
  (* The same program on a concrete input: the third row repeats a key, so it is
     rejected and the table keeps the two rows it accepted. *)
  Definition demo_store : clocals :=
    map.put map.empty "rejected" (VList nil).

  Definition demo_env : clocals :=
    map.put map.empty "incoming"
      (VList [ VRecord [("id", VInt 1); ("name", VString "a")];
               VRecord [("id", VInt 2); ("name", VString "b")];
               VRecord [("id", VInt 1); ("name", VString "c")] ]).

  Definition demo_result : clocals :=
    interp_command (map.put demo_store "users" (VList nil)) demo_env body.

  Compute (map.get demo_result "users").
  Compute (map.get demo_result "rejected").
End WithConcreteMaps.

Compute program_py prog.
