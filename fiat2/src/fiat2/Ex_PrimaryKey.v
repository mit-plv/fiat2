From Stdlib Require Import String ZArith List.

Import ListNotations.

(* A table with a primary key, loaded one row at a time.

   The table is declared empty, which is where the constraint comes from for
   free: the quantifier ranges over no rows, so the invariant holds before the
   program runs anything.  Elaboration then inserts the check at every write to
   the table, and a write that would repeat a key runs the policy written at
   that write site instead -- here, recording the offending key and leaving the
   table alone.

   Nothing about this program is proved by hand.  The invariant comes from
   elab_prog_constr_wf, which holds for every surface program and every
   constraint; all the program contributes is that it typechecks.

let users : {id : int; name : string} list  with  unique(id)
foreach u in incoming do
    users := u :: !users
      else   rejected := u.id :: !rejected
end
*)

(* already sorted by field name, as a record type must be *)
Definition row_ty :=
  TRecord [("id", TInt); ("name", TString)].

Definition key_constrs := [ DUnique "id" ].

(* Hand-written, not generated by an LLM *)
Definition body : scommand :=
  SForeach (EVar "incoming") "u"
    (SAssign "users" (EBinop OCons (EVar "u") (ELoc "users"))
       (* the policy: the row is rejected, and its key recorded *)
       (SAssign "rejected"
          (EBinop OCons (EAccess (EVar "u") "id") (ELoc "rejected"))
          SSkip)).

Definition prog : scommand :=
  SLetConstrained "users" row_ty key_constrs body.

Section WithConcreteMaps.
  Context {width: Z} {word: word.word width} {word_ok: word.ok word}.
  Notation value := (value (width:=width)).

  Local Open Scope string.

  Instance ctenv : map.map string type := SortedListString.map _.
  Instance ctenv_ok : map.ok ctenv := SortedListString.ok _.

  Instance clocals : map.map string value := SortedListString.map _.
  Instance clocals_ok : map.ok clocals := SortedListString.ok _.

  Definition init_Gstore : ctenv :=
    map.put map.empty "rejected" (TList TInt).

  Definition init_Genv : ctenv :=
    map.put map.empty "incoming" (TList row_ty).

  Definition body_Gstore : ctenv :=
    map.put init_Gstore "users" (TList row_ty).

  (* The core command the surface program elaborates to, and the one the rest
     of the pipeline sees. *)
  Definition core_prog : command := elab nil (get_free_vars init_Genv) prog.

  Definition core_body : command :=
    elab [("users", (row_ty, key_constrs))] (get_free_vars init_Genv) body.

  Compute (typecheck init_Gstore init_Genv core_prog).

  Lemma init_Gstore_wf : tenv_wf init_Gstore.
  Proof.
    unfold tenv_wf, init_Gstore; intros x t H.
    destruct (String.eqb x "rejected") eqn:E; rewrite ?eqb_eq, ?eqb_neq in *; subst.
    1:{ rewrite map.get_put_same in H. do_injection. repeat constructor. }
    1:{ rewrite map.get_put_diff in H by congruence.
        rewrite map.get_empty in H; discriminate. }
  Qed.

  Lemma row_ty_wf : type_wf row_ty.
  Proof.
    unfold row_ty.
    repeat constructor; cbn; intuition congruence.
  Qed.

  Lemma body_Gstore_wf : tenv_wf body_Gstore.
  Proof.
    unfold body_Gstore.
    apply tenv_wf_step; auto using init_Gstore_wf.
    constructor; apply row_ty_wf.
  Qed.

  Lemma init_Genv_wf : tenv_wf init_Genv.
  Proof.
    unfold tenv_wf, init_Genv; intros x t H.
    destruct (String.eqb x "incoming") eqn:E; rewrite ?eqb_eq, ?eqb_neq in *; subst.
    1:{ rewrite map.get_put_same in H. do_injection.
        constructor; apply row_ty_wf. }
    1:{ rewrite map.get_put_diff in H by congruence.
        rewrite map.get_empty in H; discriminate. }
  Qed.

  (* The declaration is well formed: "id" is a field of the row type.  That is
     all a primary key has to check, and it is decidable. *)
  Lemma key_constrs_wf : Forall (decl_wf (tenv:=ctenv) row_ty) key_constrs.
  Proof.
    unfold key_constrs, row_ty; cbn [decl_wf].
    constructor; [ | constructor ].
    exists [("id", TInt); ("name", TString)], TInt.
    split; reflexivity.
  Qed.

  (* The elaborated body typechecks.  This is the program's whole contribution
     to the theorem below. *)
  Lemma core_body_well_typed : well_typed body_Gstore init_Genv core_body.
  Proof.
    eapply command_typechecker_sound with (c := core_body).
    1: apply body_Gstore_wf.
    1: apply init_Genv_wf.
    reflexivity.
  Qed.

  (* The constraint holds of the table at every point in its lifetime: the
     declaration establishes it on the empty table, and elaboration carries it
     over every write.  Both halves come from Surface.v, not from this file. *)
  Theorem prog_keeps_id_unique : forall (store env : clocals),
      locals_wf init_Gstore store ->
      locals_wf init_Genv env ->
      holds_for_all_entries
        (value_wf_with_globals
           (constrs_hold (constrs_of_decls row_ty key_constrs)) ["users"])
        (interp_command (map.put store "users" (VList nil)) env core_body).
  Proof.
    intros.
    eapply elab_prog_constr_wf with (row_ty := row_ty) (Gstore := body_Gstore).
    1: apply body_Gstore_wf.
    1: apply init_Genv_wf.
    1: apply row_ty_wf.
    1: apply incl_refl.
    1: unfold body_Gstore; rewrite_map_get_put_goal; reflexivity.
    1: apply key_constrs_wf.
    1: apply core_body_well_typed.
    1:{ unfold body_Gstore.
        apply locals_wf_step with (t := TList row_ty); auto.
        repeat constructor. }
    1: assumption.
  Qed.

  (* ---------------------------------------------------------------------
     A check constraint, to show the per-row split rule applies.

     "every row has a positive id" does not read the table, so it is a row
     constraint, and row_split_guard_sound replaces the scan the elaboration
     inserts by a single test of the row being written.  The two hypotheses
     that rule needs -- the hygiene condition and row_constr_wf -- are
     discharged here on a concrete body, which is the point of stating them
     this way.
     --------------------------------------------------------------------- *)
  Definition positive_id : constr :=
    mk_constr "_r" (EBinop OLess (EAtom (AInt 0)) (EAccess (EVar "_r") "id")).

  Lemma positive_id_hygienic : c_row positive_id <> c_all.
  Proof. unfold positive_id, c_all; cbn [c_row]. intro H; discriminate H. Qed.

  Lemma positive_id_row_wf : row_constr_wf (tenv:=ctenv) row_ty positive_id.
  Proof.
    unfold row_constr_wf, row_env, positive_id, row_ty; cbn [c_row c_body].
    econstructor.
    1: constructor.
    1: repeat constructor.
    1:{ econstructor.
        1: constructor; rewrite_map_get_put_goal; reflexivity.
        1: reflexivity. }
  Qed.

  (* A check constraint is declared with DCheck, which is how an arbitrary
     boolean expression over a row still reaches constr unchanged: every constr
     is constr_of_decl of a DCheck naming its own binder and body. *)
  Lemma positive_id_is_a_decl :
    constr_of_decl row_ty (DCheck "_r" (c_body positive_id)) = positive_id.
  Proof. reflexivity. Qed.

  (* And so it is a constraint in the ordinary sense, usable in a declaration
     alongside the primary key. *)
  Lemma positive_id_wf : constr_wf (tenv:=ctenv) row_ty positive_id.
  Proof.
    apply row_constr_wf__constr_wf.
    1: apply positive_id_hygienic.
    1: apply positive_id_row_wf.
  Qed.

  (* The same program on a concrete input: the third row repeats a key, so it
     is rejected and the table keeps the two rows it accepted. *)
  Definition demo_store : clocals :=
    map.put map.empty "rejected" (VList nil).

  Definition demo_env : clocals :=
    map.put map.empty "incoming"
      (VList [ VRecord [("id", VInt 1); ("name", VString "a")];
               VRecord [("id", VInt 2); ("name", VString "b")];
               VRecord [("id", VInt 1); ("name", VString "c")] ]).

  Definition demo_result : clocals :=
    interp_command (map.put demo_store "users" (VList nil)) demo_env core_body.

  Compute (map.get demo_result "users").
  Compute (map.get demo_result "rejected").

  (* ---------------------------------------------------------------------
     And the optimizer, run on what the declaration elaborated to.

     The declaration is the only place the primary key is mentioned.  It made
     elaboration choose the cheap guard -- the rows of the table carrying the
     written row's key, as a bag, compared against the empty bag -- and from
     there the program is an ordinary program.  The index pipeline that follows
     is the same one Ex_Range uses, with the same heuristic shape, and it
     rewrites that filter to a single dictionary lookup without knowing a
     constraint was ever involved.
     --------------------------------------------------------------------- *)

  (* Written by hand, not generated by an LLM *)
  Definition heuristics :=
    [ AC [PushdownCollection; AnnotateCollection]
        [[DictIdx "id"]]
    ].

  Definition prog_optimized :=
    map (fun heu => apply_optimize_anno (width:=width) (heu core_prog)
                      init_Gstore init_Genv)
      heuristics.

  Compute prog_optimized.

  Theorem prog_optimized_sem : forall (store env : clocals),
      locals_wf init_Gstore store ->
      locals_wf init_Genv env ->
      forall prog', In prog' prog_optimized ->
                    interp_command store env prog'
                    = interp_command store env core_prog.
  Proof.
    unfold prog_optimized, heuristics, apply_optimize_anno; cbn [map]; intros.
    repeat destruct_In;
      try eapply transf_sound__preserve_sem;
      eauto using apply_all_transfs_sound with transf_hints.
    lazymatch goal with H: In _ [] |- _ => apply in_nil in H; intuition idtac end.
  Qed.
End WithConcreteMaps.

Compute program_py core_prog.
