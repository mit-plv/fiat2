Require Import coqutil.Map.Interface coqutil.Map.SortedListString coqutil.Word.Interface
  coqutil.Datatypes.Result.
From Stdlib Require Import List String ZArith.

Import ListNotations.

(* A table with a primary key, loaded one row at a time, optimized by the
   ordinary index pipeline.

let mut users := [] in
foreach u in incoming do
    if [ r <- !users, check(r.id == u.id), ret r ] is empty
    then users := u :: !users
    else rejected := u.id :: !rejected
end
*)

Definition row_ty := TRecord [("id", TInt); ("name", TString)].

Definition key_constrs := [ unique_constr "id" row_ty ].

(* Written by hand, not generated by an LLM *)
Definition body : command :=
  CForeach (EVar "incoming") "u"
    (CIf (fresh_guard "users" "id" "r" (EVar "u"))
       (CAssign "users" (EBinop OCons (EVar "u") (ELoc "users")))
       (CAssign "rejected"
          (EBinop OCons (EAccess (EVar "u") "id") (ELoc "rejected")))).

Definition prog : command :=
  CLetMut (EAtom (ANil (Some row_ty))) "users" body.

(* Written by hand, not generated by an LLM *)
Definition heuristics :=
  [ AC [PushdownCollection; AnnotateCollection]
      [[DictIdx "id"]]
  ].

Section WithConcreteMaps.
  Context {width: Z} {word: word.word width} {word_ok: word.ok word}.
  Notation value := (value (width:=width)).

  Local Open Scope string.

  Instance ctenv : map.map string type := SortedListString.map _.
  Instance ctenv_ok : map.ok ctenv := SortedListString.ok _.

  Instance clocals : map.map string value := SortedListString.map _.
  Instance clocals_ok : map.ok clocals := SortedListString.ok _.

  Definition init_Gstore : ctenv :=
    map.put map.empty "rejected" (TList TInt).

  Definition init_Genv : ctenv :=
    map.put map.empty "incoming" (TList row_ty).

  Compute (typecheck init_Gstore init_Genv prog).

  Definition prog_transformed :=
    map (fun heu => apply_optimize_anno (width:=width) (heu prog) init_Gstore init_Genv)
      heuristics.

  Compute prog_transformed.

  (* The optimizer's own theorem, unchanged: every program it produces means
     what the one it started from means.  Nothing here mentions a constraint --
     the rewrite that replaced the scan by a lookup is the ordinary dictionary
     index rule, whose soundness assumes only that the index is the table's,
     which the index transformation establishes. *)
  Theorem prog_transformed_sem : forall (store env : clocals),
      locals_wf init_Gstore store ->
      locals_wf init_Genv env ->
      forall prog', In prog' prog_transformed ->
                    interp_command store env prog' = interp_command store env prog.
  Proof.
    unfold prog_transformed, heuristics, apply_optimize_anno; cbn [map]; intros.
    repeat destruct_In;
      try eapply transf_sound__preserve_sem;
      eauto using apply_all_transfs_sound with transf_hints.
    lazymatch goal with H: In _ [] |- _ => apply in_nil in H; intuition idtac end.
  Qed.

  (* ---------------------------------------------------------------------
     And the constraint's own theorem: the program keeps the key unique.

     This is where the declared primary key is used, and it is used once.  The
     guard the program tests is the cheap one, which decides the constraint
     only in a store where the key already holds -- and that is exactly the
     hypothesis PWCAssign's obligation receives.
     --------------------------------------------------------------------- *)
  Definition body_Gstore : ctenv :=
    map.put init_Gstore "users" (TList row_ty).

  Lemma row_ty_wf : type_wf row_ty.
  Proof.
    unfold row_ty. repeat constructor; cbn; intuition congruence.
  Qed.

  Lemma init_Gstore_wf : tenv_wf init_Gstore.
  Proof.
    unfold tenv_wf, init_Gstore; intros k t H.
    destruct (String.eqb k "rejected") eqn:E; rewrite ?eqb_eq, ?eqb_neq in *; subst.
    1:{ rewrite map.get_put_same in H. do_injection. repeat constructor. }
    1:{ rewrite map.get_put_diff in H by congruence.
        rewrite map.get_empty in H; discriminate. }
  Qed.

  Lemma body_Gstore_wf : tenv_wf body_Gstore.
  Proof.
    unfold body_Gstore.
    apply tenv_wf_step; auto using init_Gstore_wf.
    constructor; apply row_ty_wf.
  Qed.

  Lemma init_Genv_wf : tenv_wf init_Genv.
  Proof.
    unfold tenv_wf, init_Genv; intros k t H.
    destruct (String.eqb k "incoming") eqn:E; rewrite ?eqb_eq, ?eqb_neq in *; subst.
    1:{ rewrite map.get_put_same in H. do_injection.
        constructor; apply row_ty_wf. }
    1:{ rewrite map.get_put_diff in H by congruence.
        rewrite map.get_empty in H; discriminate. }
  Qed.

  (* The policy writes to another variable, so it cannot break users' key. *)
  Lemma policy_wf : forall (A : clocals -> clocals -> Prop) (Genv : ctenv),
      map.get Genv "u" = Some row_ty ->
      parameterized_wf body_Gstore Genv
        (value_wf_with_globals (constrs_hold key_constrs) ["users"]) A
        (CAssign "rejected"
           (EBinop OCons (EAccess (EVar "u") "id") (ELoc "rejected"))).
  Proof.
    intros * H_u. econstructor.
    1:{ intros. unfold value_wf_with_globals.
        constructor; [ left; congruence | constructor ]. }
    1: unfold body_Gstore, init_Gstore; repeat rewrite_map_get_put_goal; reflexivity.
    1:{ econstructor.
        1: constructor.
        1:{ econstructor.
            1: constructor; exact H_u.
            1: reflexivity. }
        1: constructor; unfold body_Gstore, init_Gstore;
           repeat rewrite_map_get_put_goal; reflexivity. }
  Qed.

  Lemma body_wf : forall (A : clocals -> clocals -> Prop),
      parameterized_wf body_Gstore init_Genv
        (value_wf_with_globals (constrs_hold key_constrs) ["users"]) A body.
  Proof.
    intros. unfold body, key_constrs, row_ty.
    econstructor.
    1: constructor; unfold init_Genv; rewrite_map_get_put_goal; reflexivity.
    eapply (checked_cons_wf "users" "id" "r") with (kt := TInt).
    1: apply body_Gstore_wf.
    1: apply tenv_wf_step; [ apply init_Genv_wf | apply row_ty_wf ].
    1: apply row_ty_wf.
    1: reflexivity.
    1: unfold body_Gstore; rewrite_map_get_put_goal; reflexivity.
    1: constructor; rewrite_map_get_put_goal; reflexivity.
    1: reflexivity.
    1: apply policy_wf; rewrite_map_get_put_goal; reflexivity.
  Qed.

  (* The table is born empty, where the constraint holds of no rows. *)
  Lemma born_empty : forall (store : clocals),
      holds_for_all_entries
        (value_wf_with_globals (constrs_hold key_constrs) ["users"])
        (map.put store "users" (VList nil)).
  Proof.
    unfold holds_for_all_entries; intros * H_get.
    unfold value_wf_with_globals; constructor; [ | constructor ].
    destruct (String.eqb k "users") eqn:E; rewrite ?eqb_eq, ?eqb_neq in *; subst.
    1:{ right. rewrite map.get_put_same in H_get. do_injection.
        apply constrs_hold_nil. }
    1: left; congruence.
  Qed.

  Theorem prog_keeps_id_unique : forall (store env : clocals),
      locals_wf init_Gstore store ->
      locals_wf init_Genv env ->
      holds_for_all_entries
        (value_wf_with_globals (constrs_hold key_constrs) ["users"])
        (interp_command (map.put store "users" (VList nil)) env body).
  Proof.
    intros * H_store H_env.
    eapply parameterized_wf__preserve_P with
      (Gstore := body_Gstore) (Genv := init_Genv) (A := fun _ _ => True).
    1: apply body_Gstore_wf.
    1: apply init_Genv_wf.
    1: apply body_wf.
    1: exact I.
    1:{ unfold body_Gstore. apply locals_wf_step with (t := TList row_ty); auto.
        repeat constructor. }
    1: assumption.
    1: apply born_empty.
  Qed.
End WithConcreteMaps.
