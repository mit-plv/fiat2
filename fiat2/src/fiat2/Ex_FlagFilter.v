Definition prog := (CLetMut (EVar "users_tbl") "users" (CForeach (EVar "queries") "q" (CIf (EBinop OEq (EAccess (EVar "q") "type") (EAtom (AInt 0))) (CSeq (CAssign "users" (EBinop OCons (EAccess (EVar "q") "new_user") (ELoc "users"))) (CAssign "outputs" (EBinop OCons (EAtom (AString "User added\n")) (ELoc "outputs")))) (CLet (EUnop OLength (EFlatmap LikeList (ELoc "users") "u" (EIf (EAccess (EVar "u") "is_active") (EBinop OCons (EVar "u") (EAtom (ANil None))) (EAtom (ANil None))))) "n" (CAssign "outputs" (EBinop OCons (EBinop OConcatString (EAtom (AString "Active users: ")) (EBinop OConcatString (EUnop OIntToString (EVar "n")) (EAtom (AString "\n")))) (ELoc "outputs"))))))).

(* Written by hand, not generated by an LLM.

   The same program twice, with the same index asked for both times.  The
   only difference is whether the flag filter is normalised into an equality
   first.  Without it no index rule matches the predicate and the filter is
   left as a scan; with it the existing dictionary index answers the query by
   one lookup.  The normalisation runs first, so it is last in the list. *)
Definition heuristics :=
  [ AC [PushdownCollection; AnnotateCollection; FlagFilterToEq]
      [[DictIdx "is_active"]]
  ; AC [PushdownCollection; AnnotateCollection]
      [[DictIdx "is_active"]]
  ].

Definition row_ty_users :=
  TRecord (record_sort [("id", TInt); ("is_active", TBool)]).

Definition query_ty :=
  TRecord (record_sort [("type", TInt); ("new_user", row_ty_users)]).

Section WithConcreteMaps.
  Context {width: Z} {word: word.word width} {word_ok: word.ok word}.
  Notation value := (value (width:=width)).

  Local Open Scope string.

  Instance ctenv : map.map string type := SortedListString.map _.
  Instance ctenv_ok : map.ok ctenv := SortedListString.ok _.

  Instance clocals : map.map string value := SortedListString.map _.
  Instance clocals_ok : map.ok clocals := SortedListString.ok _.

  Definition init_Gstore : ctenv :=
    map.put map.empty "outputs" (TList TString).

  Definition init_Genv : ctenv :=
    map.put (map.put map.empty
               "users_tbl" (TList row_ty_users))
      "queries" (TList query_ty).

  Compute (typecheck init_Gstore init_Genv prog).

  Definition prog_transformed := map (fun heu => apply_optimize_anno (width:=width) (heu prog) init_Gstore init_Genv) heuristics.

  (* What the normalisation makes reachable: the flag is a key, so the query
     is one lookup in the dictionary index, with no row outside the bucket
     looked at. *)
  Definition flag_probe : expr :=
    EACFold AGCount
      (EOptMatch
         (EBinop OLookup
            (EAccess (EAccess (ELoc "users") "aux_tag") "0")
            (EAtom (ABool true)))
         (EAtom (AEmptyBag None)) "b" (EVar "b")).

  (* Without it: the source filter, unchanged, over the table's list.  No
     index rule matches a bare field access as a predicate. *)
  Definition flag_scan : expr :=
    EACFold AGCount
      (EFlatmap LikeBag (EBagOf (EAccess (ELoc "users") "id_tag")) "u"
         (EIf (EAccess (EVar "u") "is_active")
            (EBinop OBagInsert (EAtom (AEmptyBag None)) (EVar "u"))
            (EAtom (AEmptyBag None)))).

  (* Two projections, so the claims below are equalities of closed terms and
     reduce with vm_compute instead of unifying a whole program against a
     pattern full of holes. *)

  (* which fields the table's record holds after installation *)
  Definition installed_fields (c : command) : list string :=
    match c with
    | CLetMut (ERecord l) _ _ => List.map fst l
    | _ => []
    end.

  Definition query_of (c : command) : option expr :=
    match c with
    | CLetMut _ _ (CForeach _ _ (CIf _ _ (CLet q _ _))) => Some q
    | _ => None
    end.

  (* With the normalisation: the predicate becomes is_active == true, which is
     the shape eq_filter_to_lookup_head reads, and the scan becomes a probe. *)
  Lemma normalised_probes :
    query_of (nth 0 prog_transformed CSkip) = Some flag_probe.
  Proof. vm_compute; reflexivity. Qed.

  (* And then nothing reads the table's list any more, so the erasure pass
     drops id_tag outright: the table IS its index.  A two-valued key is
     enough for that -- the dictionary has two buckets and together they hold
     every row. *)
  Lemma normalised_drops_the_list :
    installed_fields (nth 0 prog_transformed CSkip) = ["aux_tag"].
  Proof. vm_compute; reflexivity. Qed.

  (* Without it: the same index is installed and maintained, and the query
     still scans, because no rule matches the predicate. *)
  Lemma unnormalised_scans :
    query_of (nth 1 prog_transformed CSkip) = Some flag_scan.
  Proof. vm_compute; reflexivity. Qed.

  (* And because that scan still reads the list, the list stays -- the index
     is paid for and not used. *)
  Lemma unnormalised_keeps_the_list :
    installed_fields (nth 1 prog_transformed CSkip) = ["id_tag"; "aux_tag"].
  Proof. vm_compute; reflexivity. Qed.

  Theorem prog_transformed_sem : forall (store env : clocals),
      locals_wf init_Gstore store ->
      locals_wf init_Genv env ->
      forall prog', In prog' prog_transformed ->
                    interp_command store env prog' = interp_command store env prog.
  Proof.
    unfold prog_transformed, heuristics, apply_optimize_anno; cbn [map]; intros.
    repeat destruct_In;
      try eapply transf_sound__preserve_sem;
      eauto using apply_all_transfs_sound with transf_hints.
    lazymatch goal with H: In _ [] |- _ => apply in_nil in H; intuition idtac end.
  Qed.
End WithConcreteMaps.
